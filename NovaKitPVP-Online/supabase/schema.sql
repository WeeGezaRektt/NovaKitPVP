DROP POLICY IF EXISTS "Public can read players" ON public.players;
create policy "Public can read players" on public.players for select using (true);
DROP POLICY IF EXISTS "Owners can insert players" ON public.players;
create policy "Owners can insert players" on public.players for insert to authenticated with check (public.is_owner());
DROP POLICY IF EXISTS "Owners can update players" ON public.players;
create policy "Owners can update players" on public.players for update to authenticated using (public.is_owner()) with check (public.is_owner());
DROP POLICY IF EXISTS "Owners can delete players" ON public.players;
create policy "Owners can delete players" on public.players for delete to authenticated using (public.is_owner());

DROP POLICY IF EXISTS "Public can read tiers" ON public.player_tiers;
create policy "Public can read tiers" on public.player_tiers for select using (true);
DROP POLICY IF EXISTS "Verified staff can insert tiers" ON public.player_tiers;
create policy "Verified staff can insert tiers" on public.player_tiers for insert to authenticated with check (public.is_verified_staff());
DROP POLICY IF EXISTS "Verified staff can update tiers" ON public.player_tiers;
create policy "Verified staff can update tiers" on public.player_tiers for update to authenticated using (public.is_verified_staff()) with check (public.is_verified_staff());
DROP POLICY IF EXISTS "Owners can delete tiers" ON public.player_tiers;
create policy "Owners can delete tiers" on public.player_tiers for delete to authenticated using (public.is_owner());

DROP POLICY IF EXISTS "Staff can read own profile" ON public.staff_profiles;
create policy "Staff can read own profile" on public.staff_profiles for select to authenticated using (auth_user_id = auth.uid() or public.is_owner());

DROP POLICY IF EXISTS "Users can read own link requests" ON public.link_requests;
create policy "Users can read own link requests" on public.link_requests for select to authenticated using (auth_user_id = auth.uid());

DROP POLICY IF EXISTS "Owners can read audit logs" ON public.audit_logs;
create policy "Owners can read audit logs" on public.audit_logs for select to authenticated using (public.is_owner());

